import { it, expect, vi } from 'vitest';
import { mount } from '@vue/test-utils';
import codexLogo from '../assets/codex.svg';
import openclawLogo from '../assets/openclaw.svg';
import hermesLogo from '../assets/hermes.png';
import InstallView from '../views/InstallView.vue';
import { WorkspaceKey } from '../composables/useWorkspace';

it('shows real client brands and install steps while keeping the generic Agent card', async()=>{
  const writeText=vi.fn().mockResolvedValue();
  Object.defineProperty(navigator,'clipboard',{configurable:true,value:{writeText}});
  const wrapper=mount(InstallView,{global:{provide:{[WorkspaceKey]:{state:{user:'alice'},notify:vi.fn()}}}});
  const agent=wrapper.findAll('.install-choice')[0];
  expect(agent.find('img').exists()).toBe(false);
  await agent.trigger('click');
  const clients=wrapper.find('[aria-label="Agent 客户端"]').findAll('button');
  expect(clients[0].find('img').attributes('src')).toBe(openclawLogo);
  expect(clients[1].find('img').attributes('src')).toBe(hermesLogo);
  await clients[0].trigger('click');
  expect(wrapper.find('pre').text()).toContain('uv run');
  expect(wrapper.text()).toContain('openclaw plugins install --link ./integrations/openclaw');
  expect(wrapper.text()).toContain('"userId": "alice"');
  const copyButton=wrapper.findAll('.install-code > button')[1];
  await copyButton.trigger('click');
  expect(writeText).toHaveBeenCalledWith('openclaw plugins install --link ./integrations/openclaw');
  await clients[1].trigger('click');
  expect(wrapper.text()).toContain('integrations/install_hermes.py');
  expect(wrapper.text()).toContain('hermes memory setup');
  expect(wrapper.text()).not.toContain('openclaw plugins install');
  expect(clients.map(button => button.text())).toEqual(['OpenClaw','Hermes Agent']);
  await wrapper.findAll('.install-choice')[2].trigger('click');
  expect(wrapper.text()).toContain('DeepSeek Harness');
  expect(wrapper.text()).toContain('dsh plugin --profile web add');
  expect(wrapper.text()).toContain('userId: \"alice\"');
  expect(wrapper.text()).not.toContain('DeepSeek Harness 记忆插件尚未实现');
  expect(wrapper.text()).not.toContain('LLM_API_KEY');
  const pluginButtons=wrapper.find('[aria-label="插件客户端"]').findAll('button');
  await pluginButtons[1].trigger('click');
  expect(pluginButtons[1].find('img').attributes('src')).toBe(codexLogo);
  expect(wrapper.text()).toContain('Codex 专用插件与 MCP 适配尚未实现');
  wrapper.unmount();
});
