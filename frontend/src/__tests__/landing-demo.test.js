import { afterEach, it, expect, vi } from 'vitest';
import { mount } from '@vue/test-utils';
import LandingDemo from '../components/LandingDemo.vue';
let wrapper;
afterEach(()=>{wrapper?.unmount();wrapper=null;vi.useRealTimers();vi.unstubAllGlobals();});
const setup=()=>{wrapper=mount(LandingDemo,{global:{stubs:{RouterLink:{template:'<a><slot /></a>'}}}});return wrapper;};
it('automatically cycles every scene without controls or network calls and cleans up',async()=>{
 vi.useFakeTimers();vi.stubGlobal('IntersectionObserver',undefined);
 const fetch=vi.fn();vi.stubGlobal('fetch',fetch);
 setup();
 expect(wrapper.findAll('button')).toHaveLength(0);
 expect(wrapper.findAll('.ld-bubble')).toHaveLength(1);
 await vi.advanceTimersByTimeAsync(1300);
 expect(wrapper.findAll('.ld-bubble')).toHaveLength(2);
 await vi.advanceTimersByTimeAsync(5200);
 expect(wrapper.find('.ld-tabs .active').text()).toBe('记忆演化');
 expect(wrapper.find('.ld-result strong').text()).toBe('喜欢喝茶');
 await vi.advanceTimersByTimeAsync(5200);
 expect(wrapper.find('.ld-result strong').text()).toBe('更喜欢咖啡');
 expect(wrapper.find('.ld-result p').text()).toContain('历史');
 await vi.advanceTimersByTimeAsync(1300);
 expect(wrapper.find('.ld-tabs .active').text()).toBe('可追溯管理');
 await vi.advanceTimersByTimeAsync(6500);
 expect(wrapper.find('.ld-tabs .active').text()).toBe('选择性记忆');
 expect(fetch).not.toHaveBeenCalled();
 wrapper.unmount();wrapper=null;
 expect(vi.getTimerCount()).toBe(0);
});
it('waits while outside the viewport and resumes automatically when visible',async()=>{
 vi.useFakeTimers();let onIntersection;
 vi.stubGlobal('IntersectionObserver',class{constructor(fn){onIntersection=fn;}observe(){}disconnect(){}});
 setup();
 await vi.advanceTimersByTimeAsync(2600);
 expect(wrapper.findAll('.ld-bubble')).toHaveLength(1);
 onIntersection([{isIntersecting:true}]);
 await vi.advanceTimersByTimeAsync(1300);
 expect(wrapper.findAll('.ld-bubble')).toHaveLength(2);
 onIntersection([{isIntersecting:false}]);
 await vi.advanceTimersByTimeAsync(3900);
 expect(wrapper.findAll('.ld-bubble')).toHaveLength(2);
});
