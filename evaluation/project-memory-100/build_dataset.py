def main():
    cases = []
    for memory, name, definition, examples in GROUPS:
        assert len(examples) == 25
        for example, reason in examples:
            cases.append(
                {
                    "id": f"{len(cases) + 1:03d}",
                    "memory_type": memory,
                    "memory_name": name,
                    "example": example,
                    "why": reason,
                    "status": "not_run",
                }
            )
    assert len(cases) == len({c["example"] for c in cases}) == 100
    data = {
        "name": "四种记忆的100个生活化例子",
        "version": "examples-v3",
        "origin": "project_authored",
        "status": "review_only_not_run",
        "purpose": "用日常例子帮助理解并初步区分四种记忆内容；这是概念示例集，不是系统能力验收报告。",
        "important_note": "程序性记忆用人的熟练技能作类比。这些句子描述技能，但句子本身不等于已经安装的智能体程序；工作记忆的例子强调当下保持和使用信息的情境，不是指这些句子作为历史叙述永远只能有一个标签。",
        "definitions": {memory: definition for memory, _, definition, _ in GROUPS},
        "model_calls": 0,
        "cases": cases,
    }
    (ROOT / "cases.json").write_text(
        json.dumps(data, ensure_ascii=False, indent=2) + "\n"
    )
    lines = [
        "# 四种记忆：100 个生活化例子",
        "",
        "每类 25 条，只看“例子”和“为什么属于这类”。这是帮助理解四种记忆的概念示例稿，尚未跑模型测试。",
        "",
        "> 这里说的是例子中表现出的记忆：工作是眼下暂时保持，情景是亲历的事情，语义是知道的事实，程序是已经掌握的技能。人的技能用于帮助理解；它不代表本项目已经安装了骑车、游泳等能力。",
        "",
        "[JSON 数据](cases.json) · [较复杂的上一版留档](archive/review-v2/review.md)",
        "",
    ]
    for memory, name, definition, examples in GROUPS:
        lines += [
            f"## {name}",
            "",
            definition,
            "",
            "|编号|例子|一句解释|",
            "|---|---|---|",
        ]
        for c in cases:
            if c["memory_type"] == memory:
                lines.append(f"|{c['id']}|{c['example']}|{c['why']}|")
        lines.append("")
    lines += [
        "## 看例子时的一个小区别",
        "",
        "- “我今天包了饺子”描述一次经历，重点是情景。",
        "- “我已经会熟练包饺子”强调掌握技能，重点是程序。",
        "- “饺子是一种食物”是知道的知识，重点是语义。",
        "- “包这一盘时，先记着还差两张饺子皮”是眼下暂时保持的信息，重点是工作。",
        "",
        "这些标签是示例的关注重点。若真正处理用户输入，“我会骑车”这句话也可以作为有来源的用户能力事实存入语义知识；不能直接据此认定智能体自己获得了骑车程序。",
        "",
    ]
    (ROOT / "review.md").write_text("\n".join(lines) + "\n")
    counts = dict(Counter(c["memory_type"] for c in cases))
    report = {
        "examples": 100,
        "by_type": counts,
        "unique_ids": len({c["id"] for c in cases}),
        "unique_examples": len({c["example"] for c in cases}),
        "model_calls": 0,
        "system_behavior_evaluated": False,
    }
    (ROOT / "validation.json").write_text(
        json.dumps(report, ensure_ascii=False, indent=2) + "\n"
    )
    print(json.dumps(report, ensure_ascii=False))


if __name__ == "__main__":
    main()
